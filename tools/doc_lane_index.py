#!/usr/bin/env python3
"""Regenerate docs/lanes/INDEX.md, the index of every flat lane note.

Stdlib only. Run from anywhere:

    python3 -I tools/doc_lane_index.py          # rewrite docs/lanes/INDEX.md
    python3 -I tools/doc_lane_index.py --check  # exit 1 if it is out of date

A lane note is `docs/lanes/<name>.md` (not README.md, not INDEX.md). The
table groups notes by the letters at the start of the name, which is the
series the lane belonged to (cp13 and cp41 are both "cp"), and shows each
note's title (its first heading), size, and whether Rust, Python or shell
sources cite it. The doc lint does not require a row per note, so a stale
index is harmless; the coordinator regenerates it at the end of a wave.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANES = os.path.join(ROOT, "docs", "lanes")
OUT = os.path.join(LANES, "INDEX.md")
SKIP = {"target", ".git", "out", "var", "logs", "__pycache__"}

# What a series prefix stands for, where a doc in this tree says so.
SERIES = {
    "cp": "content packets (docs/content/plan.md)",
    "ip": "improvement packets (docs/review/plan.md)",
    "soc": "the society: bot minds, alliances, contacts, wars",
    "doc": "doctrines (docs/archive/plan-living-world.md)",
    "cap": "capital ships and jump drives",
    "hk": "hacking",
    "mn": "moons and reactions",
    "ft": "fighters",
    "fe": "the fluid economy",
    "sec": "security status, CONCORD, hardening",
    "sov": "sovereignty",
    "k": "combat depth: ewar, boosts, logistics, pods",
    "x": "economy depth: insurance, skills, salvage",
    "t3": "tech 3",
    "ci": "client CI (docs/guides/client-ci.md)",
    "evejs": "EvEJS research (facts only; the review itself is docs/evejs/review/)",
}


def cited_by_code():
    names = set()
    pat = re.compile(r"docs/lanes/([A-Za-z0-9_.-]+)\.md")
    for d, dirs, files in os.walk(ROOT):
        dirs[:] = [x for x in dirs if x not in SKIP and x != "docs"]
        for f in files:
            if f.endswith((".rs", ".py", ".sh", ".toml", ".in")):
                try:
                    with open(os.path.join(d, f), encoding="utf-8", errors="replace") as fh:
                        names.update(pat.findall(fh.read()))
                except OSError:
                    pass
    return names


def title_of(path):
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            if line.startswith("#"):
                t = line.lstrip("#").strip().replace("|", "\\|")
                return re.sub(r"^(Lane|LANE)\s*:?\s*", "", t)[:110]
    return ""


def series(name):
    m = re.match(r"[a-z]+", name)
    return m.group(0) if m else "other"


def build():
    cited = cited_by_code()
    groups = {}
    for f in sorted(os.listdir(LANES)):
        if not f.endswith(".md") or f in ("README.md", "INDEX.md"):
            continue
        name = f[:-3]
        groups.setdefault(series(name), []).append(name)
    # Single-note series go together, so the index is not 150 headings long.
    small = sorted(k for k, v in groups.items() if len(v) < 3 and k not in SERIES)
    other = sorted(n for k in small for n in groups.pop(k))
    out = [
        "# Lane notes: the index",
        "",
        "Generated by `tools/doc_lane_index.py`; do not edit by hand. Every file is a",
        "finished lane's hand-off note (see `docs/lanes/README.md` for how lanes work and",
        "rule 16 for the header a note carries). They are **history**: the code and",
        "`docs/port-tracker.md` are the current state. A note marked `code` is cited by",
        "a source file, so its path must keep working. The doc index is `docs/README.md`.",
        "",
        f"{sum(len(v) for v in groups.values()) + len(other)} notes.",
        "",
    ]

    def table(names):
        out.append("| note | title | KB | cited |")
        out.append("|---|---|---|---|")
        for n in names:
            p = os.path.join(LANES, n + ".md")
            kb = max(1, os.path.getsize(p) // 1000)
            out.append(f"| `docs/lanes/{n}.md` | {title_of(p)} | {kb} | {'code' if n in cited else ''} |")
        out.append("")

    for k in sorted(groups):
        what = SERIES.get(k, "")
        out.append(f"## {k}" + (f": {what}" if what else ""))
        out.append("")
        table(groups[k])
    out.append("## Other (series of one or two notes)")
    out.append("")
    table(other)
    return "\n".join(out)


def main():
    text = build()
    if "--check" in sys.argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                same = f.read() == text
        except OSError:
            same = False
        sys.exit(0 if same else 1)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
