#!/usr/bin/env bash
# The friends' tunnel: sshd in a container (O18, IP22-a; RR1 H4).
#
#   tools/tunnel.sh up [--port N] [--listen ADDR]   # build the image, start sshd
#   tools/tunnel.sh down                            # stop and remove the container
#   tools/tunnel.sh add-key FRIEND.pub [NAME]       # allow one friend's key
#   tools/tunnel.sh remove-key NAME                 # revoke it (by the NAME it was added as)
#   tools/tunnel.sh status                          # container, port, keys, host key
#   tools/tunnel.sh host-key                        # the line a friend needs once
#   tools/tunnel.sh config [--port N] [--listen ADDR]   # print the sshd_config
#
# This is the ONLY way into the owner's server from outside. Forward this
# port on the router and nothing else: never 26000, 26001, 5222 or 5223.
# Keys only (no password, no keyboard-interactive), one forced user `eve`,
# no TTY, no shell (ForceCommand /bin/false, MaxSessions 0), and local TCP
# forwarding to exactly 127.0.0.1:26001 (the friends' listener of
# `tools/serve.sh --friends`), 127.0.0.1:5223 (its chat) and 127.0.0.1:8443
# (the public-gateway stub `serve.sh --friends` starts). Never
# GatewayPorts, never remote or unix-socket forwarding. Each key line also
# carries `restrict,port-forwarding,permitopen=...` so a key copied into some
# other sshd is no wider.
#
# The container: --network host (it must reach the host's loopback), sshd as
# the owner's uid (never root), every capability dropped, no-new-privileges,
# a read-only root and read-only mounts. State lives in var/tunnel/ (mode
# 700): sshd_config, keys/authorized_keys and keys/host/ (the host key, made
# once so a friend's known_hosts stays valid). EVE_TUNNEL_DIR overrides it.
#
# Exit codes: 0 ok, 1 failed, 2 refused usage.
# The A && B || C chains below mean "any step failed".
# shellcheck disable=SC2015
set -euo pipefail

REPO=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
DIR=${EVE_TUNNEL_DIR:-$REPO/var/tunnel}
IMAGE=eve-offline/tunnel:latest
NAME=eve-offline-tunnel
USER_NAME=eve
# The three ports a friend may reach (serve.sh FRIENDS_LISTENER and its
# --gateway). Nothing else.
PERMIT_OPEN=(127.0.0.1:26001 127.0.0.1:5223 127.0.0.1:8443)
# [A] DEFAULT_PORT: a high port, not 22, so the owner's own sshd (if any)
# and the scanners that only knock on 22 are left alone. Falsified if it
# collides with something the owner runs; --port changes it.
DEFAULT_PORT=26022
DEFAULT_LISTEN=0.0.0.0
# Key types accepted. DSA is gone from OpenSSH; RSA is allowed for old
# keys, ed25519 is what docs/guides/playing-with-friends.md tells a friend to make.
KEY_TYPES='ssh-ed25519|sk-ssh-ed25519@openssh\.com|ecdsa-sha2-nistp256|ecdsa-sha2-nistp384|ecdsa-sha2-nistp521|sk-ecdsa-sha2-nistp256@openssh\.com|ssh-rsa'

die()  { echo "tunnel.sh: $*" >&2; exit 1; }
deny() { echo "tunnel.sh: $*" >&2; exit 2; }

[[ $EUID -ne 0 ]] || deny "do not run this as root; run it as yourself"

PORT=$DEFAULT_PORT
LISTEN=$DEFAULT_LISTEN
parse_net() {
    while (( $# )); do
        case $1 in
            --port)   [[ $# -ge 2 ]] || deny "--port needs a number"; PORT=$2; shift ;;
            --listen) [[ $# -ge 2 ]] || deny "--listen needs an address"; LISTEN=$2; shift ;;
            *) deny "unknown argument: $1" ;;
        esac
        shift
    done
    [[ $PORT =~ ^[0-9]+$ ]] && (( PORT >= 1024 && PORT <= 65535 )) \
        || deny "--port must be 1024-65535 (a high port; the container is not root)"
    for p in 26000 26001 5222 5223; do
        (( PORT != p )) || deny "--port $PORT is a game or chat port; pick another"
    done
    [[ $LISTEN =~ ^[0-9.]+$ || $LISTEN =~ ^[0-9a-fA-F:]+$ ]] \
        || deny "--listen must be an IP address"
}

# The sshd_config. Every line here is asserted by tools/test_tunnel_config.py.
config() {
    cat <<EOF
# Generated by tools/tunnel.sh; do not edit (it is rewritten at every up).
Port $PORT
ListenAddress $LISTEN
HostKey /keys/host/ssh_host_ed25519_key
PidFile none
AllowUsers $USER_NAME
PermitRootLogin no
AuthenticationMethods publickey
PubkeyAuthentication yes
AuthorizedKeysFile /keys/authorized_keys
AuthorizedPrincipalsFile none
AuthorizedKeysCommand none
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitEmptyPasswords no
HostbasedAuthentication no
StrictModes yes
PermitTTY no
X11Forwarding no
AllowAgentForwarding no
AllowStreamLocalForwarding no
AllowTcpForwarding local
PermitOpen ${PERMIT_OPEN[*]}
PermitListen none
GatewayPorts no
PermitTunnel no
PermitUserEnvironment no
PermitUserRC no
ForceCommand /bin/false
MaxSessions 0
MaxAuthTries 3
MaxStartups 4:50:16
LoginGraceTime 20
ClientAliveInterval 30
ClientAliveCountMax 4
TCPKeepAlive no
UseDNS no
Compression no
LogLevel VERBOSE
EOF
}

have_docker() { command -v docker >/dev/null 2>&1 || die "docker is not on PATH"; }

build() {
    have_docker
    local out
    out=$(docker build --network default -q \
        --build-arg "UID=$(id -u)" --build-arg "GID=$(id -g)" \
        -t "$IMAGE" -f "$REPO/containers/tunnel.Dockerfile" "$REPO/containers" 2>&1) \
        || { printf '%s\n' "$out" >&2; die "docker build failed"; }
}

prepare_dir() {
    umask 077
    mkdir -p "$DIR/keys/host"
    chmod 700 "$DIR" "$DIR/keys" "$DIR/keys/host"
    [[ -e $DIR/keys/authorized_keys ]] || : > "$DIR/keys/authorized_keys"
    chmod 600 "$DIR/keys/authorized_keys"
}

running() { docker ps -q --filter "name=^/${NAME}\$" 2>/dev/null | grep -q .; }

cmd_up() {
    parse_net "$@"
    build
    prepare_dir
    running && die "already up (tools/tunnel.sh down first, to change the port)"
    docker rm -f "$NAME" >/dev/null 2>&1 || true
    if [[ ! -s $DIR/keys/host/ssh_host_ed25519_key ]]; then
        # Made once, in the container (nothing on the host), and kept.
        docker run --rm --network none --cap-drop ALL --security-opt no-new-privileges \
            --user "$(id -u):$(id -g)" -v "$DIR/keys/host:/out" "$IMAGE" \
            ssh-keygen -q -t ed25519 -N '' -C eve-offline-tunnel -f /out/ssh_host_ed25519_key \
            || die "host key generation failed"
    fi
    config > "$DIR/sshd_config.tmp" && mv "$DIR/sshd_config.tmp" "$DIR/sshd_config"
    chmod 600 "$DIR/sshd_config"
    # Fail before starting if sshd rejects its own config.
    docker run --rm --network none --cap-drop ALL --user "$(id -u):$(id -g)" \
        -v "$DIR/sshd_config:/etc/eve-tunnel/sshd_config:ro" -v "$DIR/keys:/keys:ro" \
        "$IMAGE" /usr/sbin/sshd -t -f /etc/eve-tunnel/sshd_config \
        || die "sshd -t refused the generated config"
    docker run -d --name "$NAME" --network host \
        --user "$(id -u):$(id -g)" --cap-drop ALL --security-opt no-new-privileges \
        --read-only --tmpfs /tmp:size=1m,mode=1777 --pids-limit 64 --memory 128m \
        --log-opt max-size=5m --log-opt max-file=2 \
        -v "$DIR/sshd_config:/etc/eve-tunnel/sshd_config:ro" -v "$DIR/keys:/keys:ro" \
        "$IMAGE" /usr/sbin/sshd -D -e -f /etc/eve-tunnel/sshd_config >/dev/null \
        || die "docker run failed"
    echo "== tunnel up: sshd on $LISTEN:$PORT, user $USER_NAME, forwards to ${PERMIT_OPEN[*]} only"
    local n; n=$(grep -c . "$DIR/keys/authorized_keys" || true)
    echo "   keys: $n (tools/tunnel.sh add-key FRIEND.pub NAME)"
    (( n > 0 )) || echo "   no key yet: nobody can log in until you add one"
    echo "   router: forward TCP $PORT to this machine, and nothing else"
    echo "   send each friend: your address, port $PORT, and the line from tools/tunnel.sh host-key"
}

cmd_down() {
    [[ $# -eq 0 ]] || deny "down takes no arguments"
    have_docker
    if docker rm -f "$NAME" >/dev/null 2>&1; then echo "== tunnel down"; else echo "== tunnel was not up"; fi
}

# One public key line, validated, with the restrict options prepended.
# Prints the authorized_keys line on stdout.
key_line() {
    local file=$1 name=$2 lines line type blob
    [[ -f $file ]] || deny "no such file: $file"
    grep -q 'PRIVATE KEY' "$file" && deny "$file is a PRIVATE key: ask your friend for the .pub"
    lines=$(grep -c . "$file" || true)
    [[ $lines -eq 1 ]] || deny "$file must hold exactly one key line (it has $lines)"
    line=$(grep . "$file" | tr -d '\r')
    [[ $line =~ ^($KEY_TYPES)\ ([A-Za-z0-9+/]+={0,2})(\ .*)?$ ]] \
        || deny "$file is not a plain public key line (a key type first, no options)"
    type=${BASH_REMATCH[1]}
    blob=${BASH_REMATCH[2]}
    # The blob names its own type: it must agree with the line's.
    local inner
    inner=$(printf '%s' "$blob" | base64 -d 2>/dev/null | head -c 64 | tr -c 'A-Za-z0-9@.-' ' ' | awk '{print $1}') || true
    [[ $inner == "$type" ]] || deny "$file: the key blob does not decode to a $type key"
    local opts="restrict,port-forwarding"
    local p
    for p in "${PERMIT_OPEN[@]}"; do opts+=",permitopen=\"$p\""; done
    printf '%s %s %s eve-offline:%s\n' "$opts" "$type" "$blob" "$name"
}

cmd_add_key() {
    [[ $# -ge 1 && $# -le 2 ]] || deny "usage: add-key FRIEND.pub [NAME]"
    local file=$1 name=${2:-}
    if [[ -z $name ]]; then
        name=$(basename "$file" .pub)
    fi
    [[ $name =~ ^[A-Za-z0-9._-]{1,32}$ ]] || deny "NAME must be 1-32 of [A-Za-z0-9._-]"
    local line; line=$(key_line "$file" "$name")
    prepare_dir
    local ak=$DIR/keys/authorized_keys blob
    blob=$(awk '{print $3}' <<<"$line")
    if grep -qF " $blob " "$ak"; then deny "that key is already allowed"; fi
    if grep -q " eve-offline:$name\$" "$ak"; then deny "a key named $name is already allowed (remove-key it first)"; fi
    printf '%s\n' "$line" >> "$ak"
    chmod 600 "$ak"
    echo "== allowed $name (forwarding to ${PERMIT_OPEN[*]} only); takes effect at its next login"
}

cmd_remove_key() {
    [[ $# -eq 1 ]] || deny "usage: remove-key NAME"
    local name=$1 ak=$DIR/keys/authorized_keys
    [[ $name =~ ^[A-Za-z0-9._-]{1,32}$ ]] || deny "NAME must be 1-32 of [A-Za-z0-9._-]"
    [[ -f $ak ]] && grep -q " eve-offline:$name\$" "$ak" || die "no key named $name"
    grep -v " eve-offline:$name\$" "$ak" > "$ak.tmp" || true
    chmod 600 "$ak.tmp" && mv "$ak.tmp" "$ak"
    echo "== removed $name; new logins are refused (an open session lasts until it drops: tools/tunnel.sh down && up)"
}

cmd_host_key() {
    [[ $# -eq 0 ]] || deny "host-key takes no arguments"
    local pub=$DIR/keys/host/ssh_host_ed25519_key.pub
    [[ -s $pub ]] || die "no host key yet (tools/tunnel.sh up makes it)"
    awk '{print $1, $2}' "$pub"
}

cmd_status() {
    [[ $# -eq 0 ]] || deny "status takes no arguments"
    have_docker
    if running; then
        local port; port=$(awk '$1=="Port"{print $2}' "$DIR/sshd_config" 2>/dev/null || true)
        echo "tunnel: up (container $NAME, sshd port ${port:-?})"
    else
        echo "tunnel: down"
    fi
    local ak=$DIR/keys/authorized_keys
    if [[ -s $ak ]]; then
        echo "keys:"; sed -n 's/.* eve-offline:\(.*\)$/  \1/p' "$ak"
    else
        echo "keys: none"
    fi
    [[ -s $DIR/keys/host/ssh_host_ed25519_key.pub ]] && echo "host key: $(cmd_host_key)"
    if command -v ss >/dev/null 2>&1; then
        if ss -Hltn 'sport = :26001' 2>/dev/null | grep -q .; then
            echo "friends' listener 127.0.0.1:26001: listening"
        else
            echo "friends' listener 127.0.0.1:26001: not listening (tools/serve.sh --friends)"
        fi
    fi
}

verb=${1:-}
[[ -n $verb ]] || deny "usage: tunnel.sh up|down|add-key|remove-key|status|host-key|config"
shift
case $verb in
    up)          cmd_up "$@" ;;
    down)        cmd_down "$@" ;;
    add-key)     cmd_add_key "$@" ;;
    remove-key)  cmd_remove_key "$@" ;;
    status)      cmd_status "$@" ;;
    host-key)    cmd_host_key "$@" ;;
    config)      parse_net "$@"; config ;;
    -h|--help)   sed -n '2,10p' "$0" ;;
    *) deny "unknown verb: $verb (up|down|add-key|remove-key|status|host-key|config)" ;;
esac
