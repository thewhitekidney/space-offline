/// Why a purchase was refused (the client sees only a falsy answer).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BuyError {
    NoOffer,
    BadQuantity,
    NoRecipient,
    AlreadyOwned,
    Short,
}

/// What a purchase did.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Receipt {
    pub offer: i64,
    pub qty: i64,
    pub paid: i64,
    pub tokens: Vec<i64>,
}

/// Buy `qty` of offer `offer_id` for `buyer`, delivered to character `to`.
/// Under the world lock: debits the buyer's vault under `nes:<key>`, queues
/// one token per item product (quantity `product.qty * qty`) for the
/// recipient's user, applies services, and queues the balance notice and
/// `OnRedeemingQueueUpdated`. Nothing changes on `Err`.
pub fn buy(
    reg: &mut Registry,
    buyer: i64,
    offer_id: i64,
    qty: i64,
    to: i64,
    message: &str,
    now: u64,
) -> Result<Receipt, BuyError> {
    let offer = catalogue(reg)
        .offer(offer_id)
        .cloned()
        .ok_or(BuyError::NoOffer)?;
    if !(1..=MAX_QTY).contains(&qty) || (offer.single && qty != 1) {
        return Err(BuyError::BadQuantity);
    }
    if reg.character(to).is_none() {
        return Err(BuyError::NoRecipient);
    }
    let payer = crate::nes_vault::key_of(reg, buyer);
    let owner = crate::nes_vault::key_of(reg, to);
    if offer.single && once(reg.deltas(), owner, &offer.key) {
        return Err(BuyError::AlreadyOwned);
    }
    let paid = offer.price * qty;
    let entry = crate::nes_vault::debit(
        reg.deltas_mut(),
        payer,
        paid,
        &format!("nes:{}", offer.key),
        now,
    )
    .map_err(|_| BuyError::Short)?;
    let message: String = message.chars().take(MAX_MESSAGE).collect();
    let created = crate::pyutil::filetime_now();
    let mut ids = Vec::new();
    for p in &offer.products {
        match p.service {
            None => {
                let name = catalogue(reg)
                    .item(p.type_id)
                    .map_or_else(|| offer.name.clone(), |t| t.name.to_owned());
                ids.push(add_token(
                    reg.deltas_mut(),
                    Token {
                        id: 0,
                        user: owner,
                        to,
                        type_id: p.type_id,
                        qty: p.qty * qty,
                        offer: offer.key.clone(),
                        name,
                        message: message.clone(),
                        created,
                        from: buyer,
                    },
                ));
            }
            Some(Service::BonusRemap) => {
                crate::skill_queue::grant_bonus_remaps(reg, to, p.qty * qty);
            }
        }
    }
    if offer.single {
        reg.deltas_mut().put(
            KIND_TOKEN,
            once_key(owner, &offer.key),
            vec!["1".to_owned()],
        );
    }
    crate::nes_vault::announce(reg, payer, &entry);
    if !ids.is_empty() {
        // The queue is the account's, so every pilot of it refreshes.
        let to = crate::nes_vault::pilots_of(reg, owner);
        reg.push(QueueUpdated { to });
    }
    reg.mark_dirty();
    Ok(Receipt {
        offer: offer.id,
        qty,
        paid,
        tokens: ids,
    })
}

/// `OnRedeemingQueueUpdated`: the redeem window re-reads its tokens.
#[derive(Debug, Clone)]
pub struct QueueUpdated {
    pub to: Vec<i64>,
}

impl crate::notify::Push for QueueUpdated {
    fn to_push(&self) -> (&'static str, Vec<PyValue>) {
        ("OnRedeemingQueueUpdated", vec![])
    }

    fn audience(&self) -> Option<Vec<i64>> {
        Some(self.to.clone())
    }
}

fn now_secs() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0, |d| d.as_secs())
}

/// `storeManager.buy_offer(offer_id, currency, qty, from_character_id=,
/// to_character_id=, message=, is_game_time=, store_id=)`: a truthy dict on
/// success, `False` otherwise (`vgsClient` raises `PurchaseFailedError` on a
/// falsy answer).
pub fn buy_arm(reg: &mut Registry, req: &Request<'_>) -> Result<PyValue, ServiceError> {
    let kw = |n: &str| crate::space_state::kwarg(req.kwargs, n);
    let (Some(PyValue::Int(offer)), Some(actor)) = (req.args.first(), req.actor) else {
        return Ok(PyValue::Bool(false));
    };
    let currency = req
        .args
        .get(1)
        .and_then(crate::pyutil::as_bytes)
        .unwrap_or(b"");
    let qty = match req.args.get(2) {
        Some(PyValue::Int(q)) => *q,
        _ => 1,
    };
    if currency != CURRENCY.as_bytes() || matches!(kw("is_game_time"), Some(PyValue::Bool(true))) {
        return Ok(PyValue::Bool(false));
    }
    let to = match kw("to_character_id") {
        Some(PyValue::Int(c)) if *c != 0 => *c,
        _ => actor,
    };
    let message = kw("message")
        .and_then(crate::pyutil::as_bytes)
        .map(|b| String::from_utf8_lossy(b).into_owned())
        .unwrap_or_default();
    match buy(reg, actor, *offer, qty, to, &message, now_secs()) {
        Ok(r) => Ok(pydict(vec![
            ("offerID", PyValue::Int(r.offer)),
            ("qty", PyValue::Int(r.qty)),
        ])),
        Err(_) => Ok(PyValue::Bool(false)),
    }
}

/// `vaultManager.get_account_balance('PLX')`: whole PLEX **[A]** (a vault
/// window showing 100 times this would falsify it).
pub fn account_balance(reg: &Registry, actor: Option<i64>) -> PyValue {
    let user = session_user(reg, actor);
    PyValue::Int(user.map_or(0, |u| crate::nes_vault::balance(reg.deltas(), u)))
}

