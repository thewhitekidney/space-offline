    fn claim_as(
        reg: &mut Registry,
        caller: Caller,
        ids: Vec<PyValue>,
        ch: i64,
    ) -> Result<PyValue, ServiceError> {
        let args = [PyValue::List(ids), PyValue::Int(ch)];
        let req = request("ClaimRedeemTokens", &args, None);
        reg.dispatch_as(caller, &req)
    }

    fn units_of(reg: &Registry, ty: i64) -> i64 {
        reg.store()
            .items()
            .iter()
            .filter(|i| i.type_id == ty)
            .map(|i| i.quantity)
            .sum()
    }

