//! **The in-game store (NES) backend** (L1 NES-BACKEND,
//! `handback/r-nes-econ/report.md` §2.1): the catalogue, a purchase, and the
//! redeem queue that delivers it.
//!
//! The store is machoNet, not the gateway **[V]** (`vgs/client/store.py` →
//! `vgsClient.py`): `storeManager.get_offers / get_categories / get_products`
//! and `buy_offer`, paid in PLEX from the per-user vault ([`crate::nes_vault`]).
//! Items arrive as **redeem tokens** (`userSvc.GetRedeemTokens /
//! ClaimRedeemTokens / TrashRedeemTokens`), claimed in a station. The newer
//! gateway store (`eve_public.store.targetaudience.*`) is behind the flag
//! `eve_tao_enabled`, default off, and is left dormant: nothing here depends
//! on it.
//!
//! ## The catalogue
//!
//! Authored (`content/store/`): `categories.tsv` (the tree and its words),
//! `offers.tsv` (what is sold, the price, the selector), `hullclass.tsv`
//! (which ship groups price as which SKIN class). Generated by
//! `tools/content_store.py` into the bundle: `store/catalogue.tsv` (one row
//! per product, selectors resolved to type ids and names) and `store/types.tsv`
//! (the item types the store delivers, which `typedata.tsv` does not carry:
//! PLEX, the extractor, SKIN licences). With no bundle the catalogue is empty
//! and `storeManager` answers its old truthy placeholder.
//!
//! **Owner decisions (issue #35):** the store sells no hulls, no MCT, no
//! injectors; SKINs are permanent licences priced by hull class; the extractor
//! and the bonus remap are services. Every price is an [A] content row.
//!
//! ## Delivery
//!
//! An item product becomes a **redeem token** in the recipient's user queue
//! (delta kind [`KIND_TOKEN`]); claiming it creates the item in the docked
//! station's hangar. The bonus remap is a **service**, applied to the
//! recipient at purchase (`skill_queue::grant_bonus_remaps`), so no item and
//! no token exists for it. Every purchase debits the vault under the ledger key
//! `nes:<offer key>`.
//!
//! ## What is [A]
//!
//! - `id` of an offer is a hash of its key (31 bits); `tools/content_store.py`
//!   refuses a collision.
//! - `buy_offer` answers a dict `{offerID, qty}` (truthy is all the client
//!   tests). Falsifier: the success panel not showing.
//! - `canPurchase` is computed from the buyer's vault. Falsifier: the buy
//!   button not greying.
//! - A claim away from a station is refused with `RedeemOnlyInStation`;
//!   "home station" is the station the pilot is docked in (no home-station
//!   model exists). Falsifier: TQ allowing a claim in space.
//! - `expireDateTime` None means a token never expires. Falsifier: the
//!   redeem window showing a blank or crashing on the column.
//! - A token queue is per **user** (as on TQ, where tokens are claimed to a
//!   chosen character); a gift to a character lands in that character's
//!   user's queue.

