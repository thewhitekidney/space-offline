/// The delta kind of the redeem queue (`delta_kinds::KINDS`):
/// `tok user id -> char type qty offer name message created from`,
/// `next -> n`, and `once user offer -> 1` (a single-purchase offer bought).
pub const KIND_TOKEN: &str = "nestok";

/// `vgs/common/const.py::PLX_CURRENCY` **[V]**.
pub const CURRENCY: &str = "PLX";
/// The most of one offer one call buys **[A]**.
pub const MAX_QTY: i64 = 100;
/// The longest gift message kept **[A]**.
pub const MAX_MESSAGE: usize = 200;

const OFFERS: (&str, &str) = (
    "store/catalogue.tsv",
    "#key\toffer_id\tcategory\tname\tdescription\tprice_plx\tbase_plx\tsingle\ttype_id\tqty\tservice",
);
const TYPES: (&str, &str) = (
    "store/types.tsv",
    "#type_id\tgroup_id\tcategory_id\tsingleton\tvolume\tname",
);
const CATEGORIES: (&str, &str) = ("store/categories.tsv", "path\tname\twhy");
const SHIPPED_CATEGORIES: &str = include_str!("../../../../content/store/categories.tsv");

// ---- the catalogue -------------------------------------------------------------

/// A product that is not an item.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Service {
    /// One more bonus neural remap for the recipient.
    BonusRemap,
}

impl Service {
    fn parse(s: &str) -> Option<Service> {
        match s {
            "bonus_remap" => Some(Service::BonusRemap),
            _ => None,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Product {
    /// 0 for a service.
    pub type_id: i64,
    pub qty: i64,
    pub service: Option<Service>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Offer {
    pub key: String,
    pub id: i64,
    pub category: String,
    pub name: String,
    pub description: String,
    /// Whole PLEX.
    pub price: i64,
    pub base: i64,
    pub single: bool,
    pub products: Vec<Product>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Category {
    pub path: String,
    pub name: String,
}

/// The whole store, as one content table.
#[derive(Debug, Clone, Default)]
pub struct Catalogue {
    pub offers: Vec<Offer>,
    pub categories: Vec<Category>,
    types: Vec<ItemType>,
}

fn leak(s: &str) -> &'static str {
    // Once per type at startup: the catalogue is loaded once per process.
    Box::leak(s.to_owned().into_boxed_str())
}

fn int(s: &str, what: &str) -> Result<i64, String> {
    s.parse()
        .map_err(|_| format!("{what} {s:?} is not an integer"))
}

impl Catalogue {
    /// From the data lines of `catalogue.tsv`, `types.tsv` and the authored
    /// categories. Rows of one `key` are one offer's products, in file order.
    pub fn parse<S: AsRef<str>>(
        offer_lines: &[S],
        type_lines: &[S],
        categories: Vec<Category>,
    ) -> Result<Catalogue, String> {
        let mut cat = Catalogue {
            categories,
            ..Catalogue::default()
        };
        for (i, line) in type_lines.iter().enumerate() {
            let line = line.as_ref();
            let f: Vec<&str> = line.split('\t').collect();
            let bad = |e: String| format!("{}: data line {}: {e}", TYPES.0, i + 1);
            let [id, group, category, singleton, volume, name] = f[..] else {
                return Err(bad(format!("{} fields, want 6", f.len())));
            };
            cat.types.push(ItemType {
                type_id: int(id, "type_id").map_err(bad)?,
                name: leak(name),
                group_id: int(group, "group_id").map_err(bad)?,
                category_id: int(category, "category_id").map_err(bad)?,
                singleton: singleton == "1",
                volume: volume
                    .parse()
                    .map_err(|_| bad(format!("volume {volume:?}")))?,
                capacity: 0.0,
            });
        }
        let mut by_key: BTreeMap<String, usize> = BTreeMap::new();
        for (i, line) in offer_lines.iter().enumerate() {
            let line = line.as_ref();
            let f: Vec<&str> = line.split('\t').collect();
            let bad = |e: String| format!("{}: data line {}: {e}", OFFERS.0, i + 1);
            let [
                key,
                id,
                category,
                name,
                desc,
                price,
                base,
                single,
                type_id,
                qty,
                service,
            ] = f[..]
            else {
                return Err(bad(format!("{} fields, want 11", f.len())));
            };
            let product = Product {
                type_id: int(type_id, "type_id").map_err(bad)?,
                qty: int(qty, "qty").map_err(bad)?,
                service: if service.is_empty() {
                    None
                } else {
                    Some(
                        Service::parse(service)
                            .ok_or_else(|| bad(format!("service {service:?}")))?,
                    )
                },
            };
            if product.qty < 1 || (product.type_id == 0) != product.service.is_some() {
                return Err(bad("a product is one item or one service".to_owned()));
            }
            match by_key.get(key) {
                Some(&at) => cat.offers[at].products.push(product),
                None => {
                    by_key.insert(key.to_owned(), cat.offers.len());
                    cat.offers.push(Offer {
                        key: key.to_owned(),
                        id: int(id, "offer_id").map_err(bad)?,
                        category: category.to_owned(),
                        name: name.to_owned(),
                        description: desc.to_owned(),
                        price: int(price, "price_plx").map_err(bad)?,
                        base: int(base, "base_plx").map_err(bad)?,
                        single: single == "1",
                        products: vec![product],
                    });
                }
            }
        }
        let mut ids = std::collections::BTreeSet::new();
        for o in &cat.offers {
            if o.price < 1 || !ids.insert(o.id) {
                return Err(format!(
                    "{}: offer {:?}: price below 1 or an id used twice",
                    OFFERS.0, o.key
                ));
            }
        }
        Ok(cat)
    }

    pub fn is_empty(&self) -> bool {
        self.offers.is_empty()
    }

    pub fn offer(&self, id: i64) -> Option<&Offer> {
        self.offers.iter().find(|o| o.id == id)
    }

    /// The item types the store delivers, for `item::find_in`.
    pub fn item_types(&self) -> &[ItemType] {
        &self.types
    }

    fn item(&self, type_id: i64) -> Option<&ItemType> {
        self.types.iter().find(|t| t.type_id == type_id)
    }
}

/// **Refuse to start** on a world that holds PLEX vault rows or redeem tokens
/// when the content has no store catalogue: the bundle was extracted before the
/// `store` section existed (or is another build's), so PLEX would be an
/// unknown type, withdrawals would fail and waiting tokens could never be
/// claimed, all without a word. Called once at startup (`server.rs`).
pub fn check_catalogue(reg: &Registry) -> Result<(), String> {
    if !catalogue(reg).is_empty() {
        return Ok(());
    }
    let d = reg.deltas();
    let vault = d
        .of(crate::nes_vault::KIND)
        .keys()
        .any(|k| k.first().is_some_and(|t| t == "bal"));
    let queue = d
        .of(KIND_TOKEN)
        .keys()
        .any(|k| k.first().is_some_and(|t| t == "tok"));
    if vault || queue {
        return Err(
            "the world file holds PLEX vault or redeem-queue rows but the content bundle has \
no store/catalogue.tsv; re-extract with tools/up.sh (the `store` section of tools/content.py)"
                .to_owned(),
        );
    }
    Ok(())
}

/// The item types the store delivers (`item::find_in`'s and
/// `find_type_in`'s fall-through), from `content`.
pub fn item_types_in(content: &crate::content::Content) -> &[ItemType] {
    content
        .try_get::<Catalogue>()
        .map_or(&[][..], Catalogue::item_types)
}

/// This table's registration row: one line in `content_tables::TABLES`.
pub const TABLE: TableSpec = TableSpec {
    name: "nes",
    load: boxed_load,
    fixture: boxed_fixture,
};

fn categories_of(rows: &[Row]) -> Vec<Category> {
    rows.iter()
        .map(|r| Category {
            path: r.field(0).to_owned(),
            name: r.field(1).to_owned(),
        })
        .collect()
}

fn boxed_load(src: &Sources) -> Result<Boxed, String> {
    let cats = src.authored(CATEGORIES.0, SHIPPED_CATEGORIES, CATEGORIES.1)?;
    let categories = categories_of(&cats.rows);
    let Some(b) = src.bundle else {
        // No bundle, no client data: an empty store (the placeholder answers).
        return Ok(Box::new(Catalogue {
            categories,
            ..Catalogue::default()
        }));
    };
    let offers = b.data_lines(OFFERS.0, OFFERS.1)?;
    let types = b.data_lines(TYPES.0, TYPES.1)?;
    if offers.is_empty() {
        src.note(Origin::Fixture);
    }
    Ok(Box::new(Catalogue::parse(&offers, &types, categories)?))
}

