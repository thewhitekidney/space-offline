/// The catalogue of `reg`'s content (empty when the table is absent).
fn catalogue(reg: &Registry) -> &Catalogue {
    static EMPTY: std::sync::OnceLock<Catalogue> = std::sync::OnceLock::new();
    reg.content()
        .try_get::<Catalogue>()
        .unwrap_or_else(|| EMPTY.get_or_init(Catalogue::default))
}

// ---- the catalogue as the client's JSON ------------------------------------------

/// A stable 31-bit id for a category path (FNV-1a), never 0.
pub fn category_id(path: &str) -> i64 {
    let mut h: u32 = 0x811c_9dc5;
    for b in path.bytes() {
        h ^= u32::from(b);
        h = h.wrapping_mul(0x0100_0193);
    }
    i64::from((h & 0x7fff_ffff).max(1))
}

fn uni(s: &str) -> PyValue {
    PyValue::Unicode(s.to_owned())
}

fn parent_of(path: &str) -> Option<&str> {
    path.rsplit_once('/').map(|(p, _)| p)
}

/// `get_categories`: `{id, name, href, parent: None | {id}, tags}`
/// (`create_category_from_json`). A root with no children becomes a tag on
/// the client, so the tree is sent as authored.
pub fn categories_value(c: &Catalogue) -> PyValue {
    PyValue::List(
        c.categories
            .iter()
            .map(|k| {
                pydict(vec![
                    ("id", PyValue::Int(category_id(&k.path))),
                    ("name", uni(&k.name)),
                    ("href", uni("")),
                    (
                        "parent",
                        parent_of(&k.path).map_or(PyValue::None, |p| {
                            pydict(vec![("id", PyValue::Int(category_id(p)))])
                        }),
                    ),
                    ("tags", PyValue::List(vec![])),
                ])
            })
            .collect(),
    )
}

/// The offer's category ids: its own and every ancestor's.
fn category_ids(path: &str) -> Vec<PyValue> {
    let mut out = Vec::new();
    let mut p = Some(path);
    while let Some(x) = p {
        out.push(pydict(vec![("id", PyValue::Int(category_id(x)))]));
        p = parent_of(x);
    }
    out
}

fn product_id(o: &Offer, i: usize) -> i64 {
    o.id * 16 + i as i64
}

/// `get_offers` for a pilot whose vault holds `balance` PLEX and who has
/// bought `bought` single-purchase offers (`create_offer_from_json`).
pub fn offers_value(c: &Catalogue, balance: i64, bought: &dyn Fn(&str) -> bool) -> PyValue {
    PyValue::List(
        c.offers
            .iter()
            .map(|o| {
                let products = o
                    .products
                    .iter()
                    .enumerate()
                    .map(|(i, p)| {
                        let mut kv = vec![
                            ("id", PyValue::Int(product_id(o, i))),
                            ("typeId", PyValue::Int(p.type_id)),
                            ("quantity", PyValue::Int(p.qty)),
                        ];
                        if p.type_id == 0 {
                            // A service has no type to name it.
                            kv.push(("productName", uni(&o.name)));
                            kv.push(("imageUrl", uni("")));
                        }
                        pydict(kv)
                    })
                    .collect();
                pydict(vec![
                    ("id", PyValue::Int(o.id)),
                    ("name", uni(&o.name)),
                    ("description", uni(&o.description)),
                    ("href", uni("")),
                    (
                        "offerPricings",
                        PyValue::List(vec![pydict(vec![
                            ("currency", uni(CURRENCY)),
                            ("price", PyValue::Int(o.price)),
                            ("basePrice", PyValue::Int(o.base)),
                        ])]),
                    ),
                    ("imageUrl", uni("")),
                    ("products", PyValue::List(products)),
                    ("categories", PyValue::List(category_ids(&o.category))),
                    ("label", PyValue::None),
                    (
                        "canPurchase",
                        PyValue::Bool(balance >= o.price && !(o.single && bought(&o.key))),
                    ),
                    ("singlePurchase", PyValue::Bool(o.single)),
                ])
            })
            .collect(),
    )
}

/// `get_products`: one `{id, name, href}` per product of every offer.
pub fn products_value(c: &Catalogue) -> PyValue {
    PyValue::List(
        c.offers
            .iter()
            .flat_map(|o| {
                o.products.iter().enumerate().map(move |(i, p)| {
                    let name = c
                        .item(p.type_id)
                        .map_or_else(|| o.name.clone(), |t| t.name.to_owned());
                    pydict(vec![
                        ("id", PyValue::Int(product_id(o, i))),
                        ("name", uni(&name)),
                        ("href", uni("")),
                    ])
                })
            })
            .collect(),
    )
}

/// The `storeManager` read arms. `None` when the catalogue is empty (the
/// caller answers its old truthy placeholder).
pub fn store_read(reg: &Registry, method: &str, actor: Option<i64>) -> Option<PyValue> {
    let c = catalogue(reg);
    if c.is_empty() {
        return None;
    }
    match method {
        "get_categories" => Some(categories_value(c)),
        "get_products" => Some(products_value(c)),
        "get_offers" => {
            let user = actor.map(|a| crate::nes_vault::key_of(reg, a));
            let balance = user.map_or(0, |u| crate::nes_vault::balance(reg.deltas(), u));
            let bought = |key: &str| user.is_some_and(|u| once(reg.deltas(), u, key));
            Some(offers_value(c, balance, &bought))
        }
        _ => None,
    }
}

// ---- the redeem queue -----------------------------------------------------------

fn once_key(user: i64, offer: &str) -> Vec<String> {
    vec!["once".to_owned(), user.to_string(), offer.to_owned()]
}

fn once(d: &Deltas, user: i64, offer: &str) -> bool {
    d.of(KIND_TOKEN).contains_key(&once_key(user, offer))
}

/// One waiting token.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Token {
    pub id: i64,
    pub user: i64,
    /// The character it was addressed to (a gift's recipient).
    pub to: i64,
    pub type_id: i64,
    pub qty: i64,
    pub offer: String,
    pub name: String,
    pub message: String,
    pub created: i64,
    pub from: i64,
}

fn tok_key(user: i64, id: i64) -> Vec<String> {
    vec!["tok".to_owned(), user.to_string(), format!("{id:012}")]
}

fn put_token(d: &mut Deltas, t: &Token) {
    d.put(
        KIND_TOKEN,
        tok_key(t.user, t.id),
        vec![
            t.to.to_string(),
            t.type_id.to_string(),
            t.qty.to_string(),
            t.offer.clone(),
            t.name.clone(),
            t.message.clone(),
            t.created.to_string(),
            t.from.to_string(),
        ],
    );
}

/// The tokens waiting for `user`, oldest first.
pub fn tokens(d: &Deltas, user: i64) -> Vec<Token> {
    let u = user.to_string();
    let from = vec!["tok".to_owned(), u.clone(), String::new()];
    d.of(KIND_TOKEN)
        .range(from..)
        .take_while(|(k, _)| k.len() == 3 && k[0] == "tok" && k[1] == u)
        .filter_map(|(k, v)| {
            let n = |i: usize| v.get(i)?.parse::<i64>().ok();
            Some(Token {
                id: k[2].parse().ok()?,
                user,
                to: n(0)?,
                type_id: n(1)?,
                qty: n(2)?,
                offer: v.get(3)?.clone(),
                name: v.get(4)?.clone(),
                message: v.get(5)?.clone(),
                created: n(6)?,
                from: n(7)?,
            })
        })
        .collect()
}

fn next_token_id(d: &mut Deltas) -> i64 {
    let k = vec!["next".to_owned()];
    let n = d
        .of(KIND_TOKEN)
        .get(&k)
        .and_then(|v| v.first()?.parse::<i64>().ok())
        .unwrap_or(1)
        .max(1);
    d.put(KIND_TOKEN, k, vec![(n + 1).to_string()]);
    n
}

/// Queue a token for `user`.
pub fn add_token(d: &mut Deltas, mut t: Token) -> i64 {
    t.id = next_token_id(d);
    put_token(d, &t);
    t.id
}

/// The account the call is for: the session's own (`Caller::Session`, which
/// is also who is at the select screen, where there is no actor), else the
/// actor's vault key. A server-made call with no actor is nobody's.
fn session_user(reg: &Registry, actor: Option<i64>) -> Option<i64> {
    match reg.caller() {
        crate::service::Caller::Session { user_id, .. } => Some(user_id),
        crate::service::Caller::Internal => actor.map(|a| crate::nes_vault::key_of(reg, a)),
    }
}

/// `userSvc.GetRedeemTokens`: attribute objects **[V]** (`redeemsvc`).
pub fn tokens_value(reg: &Registry, actor: Option<i64>) -> PyValue {
    let waiting = session_user(reg, actor).map_or_else(Vec::new, |u| tokens(reg.deltas(), u));
    PyValue::List(
        waiting
            .into_iter()
            .map(|t| {
                keyval(vec![
                    ("tokenID", PyValue::Int(t.id)),
                    ("massTokenID", PyValue::None),
                    ("typeID", PyValue::Int(t.type_id)),
                    ("quantity", PyValue::Int(t.qty)),
                    ("stationID", PyValue::None),
                    ("expireDateTime", PyValue::None),
                    ("blueprintInfo", PyValue::None),
                    ("blueprintRuns", PyValue::None),
                    ("isAutoInject", PyValue::Bool(false)),
                    // `redeem/data.py::is_auto_injected` and
                    // `redeemsvc.GetTokenLabel` read these on every token.
                    ("soulbound", PyValue::Bool(false)),
                    ("label", PyValue::None),
                    ("dateTime", PyValue::Int(t.created)),
                    ("name", uni(&t.name)),
                    ("description", uni(&t.message)),
                    ("imageUrl", uni("")),
                ])
            })
            .collect(),
    )
}

/// The token ids a call names: a list of `(tokenID, massTokenID)` tuples, of
/// `{tokenID: ...}` dicts, or of bare ids.
fn token_ids(arg: Option<&PyValue>) -> Vec<i64> {
    let Some(PyValue::List(v) | PyValue::Tuple(v)) = arg else {
        return Vec::new();
    };
    v.iter()
        .filter_map(|x| match x {
            PyValue::Int(n) => Some(*n),
            PyValue::Tuple(t) | PyValue::List(t) => match t.first() {
                Some(PyValue::Int(n)) => Some(*n),
                _ => None,
            },
            d @ PyValue::Dict(_) => match crate::pyutil::dict_get(d, b"tokenID") {
                Some(PyValue::Int(n)) => Some(*n),
                _ => None,
            },
            _ => None,
        })
        .collect()
}

fn user_error(key: &str) -> PyValue {
    eve_proto::user_error(key, vec![])
}

/// `userSvc.ClaimRedeemTokens(tokens, charID, useHomeStation)`: creates the
/// items in the docked station's hangar and answers `{errors, itemsCreated,
/// stationID, isk_balance, charID}` **[V]** (`characterSlots.py`,
/// `redeem/client/ui.py`). `charID` is the client's word, so the caller must
/// be allowed to play that character (the check `SelectCharacterID` makes),
/// and each token is taken from the queue **before** its item is made, so a
/// token named twice makes one item.
pub fn claim(reg: &mut Registry, req: &Request<'_>) -> Result<PyValue, ServiceError> {
    let ids = token_ids(req.args.first());
    let char_id = match req.args.get(1) {
        Some(PyValue::Int(c)) => *c,
        _ => req.actor.unwrap_or(0),
    };
    let allowed = reg
        .character(char_id)
        .is_some_and(|c| reg.may_play(reg.caller(), c));
    if !allowed {
        return Err(ServiceError::Raise(user_error("RedeemNoCharacter")));
    }
    let user = crate::nes_vault::key_of(reg, char_id);
    // Where the pilot is *now*: `Character::station_id` is never cleared on
    // undock, the roster is what says so.
    let station = reg.docked_station(char_id);
    let mine = tokens(reg.deltas(), user);
    let mut errors = Vec::new();
    let mut created = Vec::new();
    let mut seen = std::collections::BTreeSet::new();
    for id in ids {
        if !seen.insert(id) {
            continue;
        }
        let Some(t) = mine.iter().find(|t| t.id == id) else {
            errors.push((id, "RedeemTokenNotFound"));
            continue;
        };
        let Some(station) = station else {
            errors.push((id, "RedeemOnlyInStation"));
            continue;
        };
        // Take the token first; only the one that took it makes the item.
        let key = tok_key(user, id);
        let Some(row) = reg.deltas_mut().del(KIND_TOKEN, &key) else {
            errors.push((id, "RedeemTokenNotFound"));
            continue;
        };
        let at = crate::item::Slot::new(char_id, station, crate::model::FLAG_HANGAR);
        let made = reg.apply_items(&[crate::item::Edit::Create {
            type_id: t.type_id,
            quantity: t.qty,
            to: at,
        }]);
        match made {
            Ok(changes) => {
                let item = changes.iter().find_map(|c| match c {
                    crate::item::Change::Created { item_id, .. } => Some(*item_id),
                    _ => None,
                });
                created.push((item.unwrap_or(0), t.type_id, t.qty, station));
            }
            // The type is not one the world knows: put the token back.
            Err(_) => {
                reg.deltas_mut().put(KIND_TOKEN, key, row);
                errors.push((id, "RedeemTokenNotFound"));
            }
        }
    }
    Ok(pydict(vec![
        (
            "errors",
            PyValue::List(
                errors
                    .into_iter()
                    .map(|(id, key)| PyValue::Tuple(vec![PyValue::Int(id), user_error(key)]))
                    .collect(),
            ),
        ),
        (
            "itemsCreated",
            PyValue::List(
                created
                    .into_iter()
                    .map(|(item, ty, q, st)| {
                        pydict(vec![
                            ("itemID", PyValue::Int(item)),
                            ("typeID", PyValue::Int(ty)),
                            ("quantity", PyValue::Int(q)),
                            ("stationID", PyValue::Int(st)),
                        ])
                    })
                    .collect(),
            ),
        ),
        ("stationID", station.map_or(PyValue::None, PyValue::Int)),
        // The select screen's report reads these two.
        ("isk_balance", PyValue::None),
        ("charID", PyValue::Int(char_id)),
    ]))
}

/// `userSvc.TrashRedeemTokens(tokens)`: deletes them, ledgering the units as
/// `redeem_trash` (the PLEX was spent when they were bought).
pub fn trash(reg: &mut Registry, req: &Request<'_>) -> Result<PyValue, ServiceError> {
    let Some(user) = session_user(reg, req.actor) else {
        return Ok(PyValue::None);
    };
    let mine = tokens(reg.deltas(), user);
    let mut units = 0;
    for id in token_ids(req.args.first()) {
        if let Some(t) = mine.iter().find(|t| t.id == id) {
            reg.deltas_mut().del(KIND_TOKEN, &tok_key(user, id));
            units += t.qty;
        }
    }
    if units > 0 {
        crate::nes_vault::ledger_out(reg.deltas_mut(), "redeem_trash", units);
        reg.mark_dirty();
    }
    Ok(PyValue::None)
}

